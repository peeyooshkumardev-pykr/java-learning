public class loop3 {
    public static void main(String []args){
        for(int i = 2; i<=20; i=i+2){
            System.out.print(i+" ");
        }
        System.out.println();
        for(int j = 1; j<=20; j=j+2){
            System.out.print(j+" ");
        }
    }
}
